import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { readLibrary, mutateStyle } from './style-library.mjs';
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'ndt-style-test-'));
try {
  await fs.mkdir(path.join(root, 'registry'));
  await fs.copyFile(new URL('../registry/asset-taxonomy.json', import.meta.url), path.join(root, 'registry/asset-taxonomy.json'));
  const asset = { id: 'asset-a', asset_version: 'v1', source_ref: 'assets/a.svg', category: 'graphics', routes: ['ppt'], rights: 'fixture' };
  const template = { id: 'template-a', asset_version: 'v1', category: 'templates' };
  const secondTemplate = { id: 'template-b', asset_version: 'v2', category: 'templates' };
  const resource = { id: 'method-a', name: 'Semantic color roles', tags: { color: ['语义配色'] }, source_ref: 'methods/color.json', license: 'MIT', distribution: 'reference-only', reusable_parts: ['role mapping'] };
  const preview = { src: '/ndt-assets/fixture.png', label: '完整预览', boundary: 'fixture only' };
  const manifest = { name: '风格测试', assets: [{ asset_id: asset.id, asset_version: 'v1', use: '主体图形' }], templates: [{ asset_id: template.id, asset_version: 'v1', use: 'PPT', previews: [preview] }, { asset_id: secondTemplate.id, asset_version: 'v2', use: '网页', previews: [preview] }], rules: ['图形居中，文字在下方'], parameters: [{ name: '强调色', value: '蓝色', constraint: '单一强调色' }], previews: [preview] };
  const existing = { style_id: 'style-fixture' };
  const catalog = { assets: [asset, template, secondTemplate], supporting_resources: [resource], recipes: [{ id: 'old-route', asset_ids: [asset.id], resource_ids: [resource.id] }], styles: [{ id: existing.style_id, deleted_at: null, versions: [{ version: 1, status: 'candidate', approval: null, manifest: structuredClone(manifest) }] }], preview_files: ['/ndt-assets/fixture.png'] };
  await fs.writeFile(path.join(root, 'registry/design-assets.json'), JSON.stringify(catalog));
  let current = await readLibrary(root);
  const methodQuery = await readLibrary(root, { search: 'Semantic', tags: { color: ['语义配色'] }, limit: 1 });
  assert.deepEqual(methodQuery.resources, [resource]);
  assert.equal(methodQuery.resource_total, 1);
  assert.equal(methodQuery.total, 0);
  assert.deepEqual(methodQuery.recipes, catalog.recipes);
  assert.equal((await readLibrary(root, { search: 'unmatched' })).resource_total, 0);
  await assert.rejects(mutateStyle(root, { action: 'save', style_id: existing.style_id, version: 1, expected_revision: current.revision, manifest: { ...manifest, assets: [{ ...manifest.assets[0], asset_version: 'wrong' }] } }), /版本/);
  await assert.rejects(mutateStyle(root, { action: 'save', style_id: existing.style_id, version: 1, expected_revision: current.revision, manifest: { ...manifest, previews: [{ ...preview, src: '/ndt-assets/missing.png' }] } }), /未登记/);
  const originalBytes = await fs.readFile(path.join(root, 'registry/design-assets.json'));
  for (const style_id of [undefined, '', ' ', 'style-unknown']) {
    await assert.rejects(mutateStyle(root, { action: 'save', style_id, version: 1, expected_revision: current.revision, manifest }));
    assert.deepEqual(await fs.readFile(path.join(root, 'registry/design-assets.json')), originalBytes);
  }
  await assert.rejects(mutateStyle(root, { action: 'save', style_id: existing.style_id, expected_revision: current.revision, manifest }), /版本不存在/);
  assert.deepEqual(await fs.readFile(path.join(root, 'registry/design-assets.json')), originalBytes);
  const originalRevision = current.revision;
  current = await readLibrary(root);
  assert.equal((await readLibrary(root, { recommendedOnly: true })).styles.length, 0);
  await assert.rejects(mutateStyle(root, { action: 'approve', style_id: existing.style_id, version: 1, expected_revision: current.revision }), /NERO/);
  await mutateStyle(root, { action: 'approve', style_id: existing.style_id, version: 1, confirmed: true, confirmed_by: 'NERO', expected_revision: current.revision });
  current = await readLibrary(root);
  assert.equal((await readLibrary(root, { recommendedOnly: true })).styles[0].versions[0].status, 'approved');
  const approvedManifest = structuredClone(current.styles[0].versions[0].manifest);
  await assert.rejects(mutateStyle(root, { action: 'delete', style_id: existing.style_id, version: 1, expected_revision: originalRevision }), error => error.code === 'CONFLICT');
  const revision = current.revision;
  const request = { action: 'save', style_id: existing.style_id, version: 1, expected_revision: revision, manifest: { ...manifest, name: '新候选' } };
  const concurrent = await Promise.allSettled([mutateStyle(root, request), mutateStyle(root, request)]);
  assert.equal(concurrent.filter(r => r.status === 'fulfilled').length, 1);
  current = await readLibrary(root);
  assert.deepEqual(current.styles[0].versions[0].manifest, approvedManifest);
  assert.equal(current.styles[0].versions[0].status, 'approved');
  assert.equal(current.styles[0].versions[1].status, 'candidate');
  assert.equal((await readLibrary(root, { recommendedOnly: true })).styles[0].versions.length, 1);
  await mutateStyle(root, { action: 'deactivate', style_id: existing.style_id, version: 2, expected_revision: current.revision });
  current = await readLibrary(root);
  assert.equal(current.styles[0].versions[1].status, 'disabled');
  assert.equal((await readLibrary(root, { recommendedOnly: true })).styles[0].versions[0].version, 1);
  await mutateStyle(root, { action: 'delete', style_id: existing.style_id, version: 1, expected_revision: current.revision });
  current = await readLibrary(root);
  assert.equal(current.styles.length, 0);
  assert.equal((await readLibrary(root, { recommendedOnly: true })).styles.length, 0);
  const old = await readLibrary(root, { styleId: existing.style_id, version: 1 });
  assert.equal(old.styles[0].versions.length, 1);
  assert.deepEqual(old.styles[0].versions[0].manifest, approvedManifest);
  assert.deepEqual(current.assets, catalog.assets);
  assert.deepEqual(JSON.parse(await fs.readFile(path.join(root, 'registry/design-assets.json'))).recipes, catalog.recipes);
  assert.ok((await fs.readdir(path.join(root, 'registry/style-history'))).length >= 4);
  const backups = await fs.readdir(path.join(root, 'registry/style-history'));
  const original = JSON.parse(await fs.readFile(path.join(root, 'registry/style-history', originalRevision + '.json')));
  assert.deepEqual(original, catalog);
  console.log(JSON.stringify({ status: 'pass', scenarios: ['style creation unavailable with exact data preservation', 'existing style and version required', 'reference validation', 'preview boundary', 'multiple templates', 'candidate-only save', 'explicit approval', 'immutable approved manifest', 'conflict/concurrency', 'deactivation', 'soft deletion', 'historical lookup', 'asset and route preservation', 'backup restoration'], backups: backups.length }));
} finally { await fs.rm(root, { recursive: true }); }
